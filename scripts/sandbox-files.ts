// Writes src/sandbox-files.ts: what dreamwalker uploads into a sandbox, as text it can bundle. That's Pi Durable's
// environment (dist/env, which imports only Node and itself) and sandbox/helper.mjs, which runs it there. Run it
// after changing the helper or upgrading Pi Durable; test/sandbox.test.ts fails while the file is out of date.
//
//   node --no-warnings scripts/sandbox-files.ts
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ENV_FILES = ["index.js", "decode.js", "line-scan.js", "node.js", "node-watch.js"];
const here = dirname(fileURLToPath(import.meta.url));

/** The files, by their path under the sandbox's install directory. */
export function sandboxFiles() {
	const envDir = dirname(createRequire(import.meta.url).resolve("@earendil-works/pi-durable/env/node"));
	return Object.fromEntries([
		...ENV_FILES.map((name) => [`env/${name}`, readFileSync(join(envDir, name), "utf8")] as const),
		["helper.mjs", readFileSync(join(here, "../sandbox/helper.mjs"), "utf8")] as const,
	]);
}

/** The module's text: the files and a version that changes with any of them. */
export function render(files: Record<string, string>): string {
	const hash = createHash("sha256");
	for (const [path, text] of Object.entries(files)) hash.update(path).update("\0").update(text).update("\0");
	return [
		"// Generated by scripts/sandbox-files.ts from Pi Durable's dist/env and sandbox/helper.mjs. Don't edit it; run the script.",
		`export const SANDBOX_VERSION = ${JSON.stringify(hash.digest("hex").slice(0, 16))};`,
		`export const SANDBOX_FILES = ${JSON.stringify(files, null, "\t")};`,
		"",
	].join("\n");
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
	writeFileSync(join(here, "../src/sandbox-files.ts"), render(sandboxFiles()));
	console.log("wrote src/sandbox-files.ts");
}
